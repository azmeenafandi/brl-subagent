// Purpose: Branch-based git workflow for worktree runs (branch, diff, switch-back, cleanup) plus the read-only worktree probe.
/**
 * brl-subagent — Git Integration (P3)
 *
 * Branch-based git workflow for subagent isolation.
 * All git commands use execFileSync, with a 10-second default timeout.
 *
 * Issue #474 added `probeWorktree` — the READ-ONLY half: it reports what a
 * settled-failure run may have left behind, and it must not write (the index
 * refresh `git status` performs opportunistically is exactly the write the
 * caller is trying to avoid). It is also the only entry point here that never
 * throws: a probe failure is a classified value, so reporting can never change
 * a run's failure classification.
 */

import { execFileSync } from "node:child_process";
import * as fs from "node:fs";

/** Default bound for one git command (the long-standing 10 s). */
const GIT_TIMEOUT_MS = 10_000;

// ---------------------------------------------------------------------------
// Options for git commands
// ---------------------------------------------------------------------------

function gitOpts(cwd: string, timeoutMs: number = GIT_TIMEOUT_MS) {
	return {
		cwd,
		encoding: "utf-8" as const,
		timeout: timeoutMs,
		// Capture child stderr instead of inheriting it: expected git failures
		// (e.g. deleting a checked-out branch) are caught and returned as
		// {ok:false, error}; execFileSync still puts the captured stderr in the
		// thrown error's message, so real failures stay diagnosable.
		stdio: ["ignore", "pipe", "pipe"] as ["ignore", "pipe", "pipe"],
	};
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Get the current branch name.
 * Throws if the cwd is not a git repository.
 */
export function getCurrentBranch(cwd: string): string {
	const output = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], gitOpts(cwd));
	return output.trim();
}

/**
 * The starting state of HEAD, captured at spawn so teardown can restore it.
 *
 * `getCurrentBranch` alone is NOT enough to restore a detached HEAD: it
 * returns the "HEAD" pseudo-ref, so a `git checkout HEAD` teardown is a no-op
 * that stays on the work branch (stranding it and leaking the branch in CI PR
 * builds, which check out a detached HEAD). The sha + attached-ness must be
 * captured together.
 *
 * `detached` also governs DATA SAFETY at teardown (#308): a detached start has
 * no branch of its own to retain a merged work branch, so the auto-approve path
 * MUST preserve the work branch as the durable ref rather than delete it.
 */
export interface HeadState {
	/** Commit HEAD pointed at when captured. */
	sha: string;
	/** True when HEAD was detached (no symbolic ref) at capture time. */
	detached: boolean;
	/**
	 * Branch name when attached; the literal "HEAD" pseudo-ref when detached.
	 * Attached callers can pass it straight to createWorkBranch/captureDiff.
	 */
	branch: string;
}

/**
 * Capture the current HEAD state (sha + attached-ness) for later restoration.
 * Throws if the cwd is not a git repository.
 */
export function getHeadState(cwd: string): HeadState {
	const sha = execFileSync("git", ["rev-parse", "HEAD"], gitOpts(cwd)).trim();
	try {
		// Exits non-zero when HEAD is detached — that is the discriminator.
		const branch = execFileSync("git", ["symbolic-ref", "--short", "-q", "HEAD"], gitOpts(cwd)).trim();
		return { sha, detached: false, branch };
	} catch {
		return { sha, detached: true, branch: "HEAD" };
	}
}

/**
 * Resolve the repository root that contains the given directory.
 * Returns undefined when the directory is not inside a repository, or when
 * git is unavailable — callers fall back to the directory path itself.
 */
export function getRepoRoot(cwd: string): string | undefined {
	try {
		const output = execFileSync("git", ["rev-parse", "--show-toplevel"], gitOpts(cwd));
		const root = output.trim();
		return root.length > 0 ? root : undefined;
	} catch {
		return undefined;
	}
}

/**
 * Check if there are uncommitted changes in the working tree.
 */
export function hasUncommittedChanges(cwd: string): boolean {
	const output = execFileSync("git", ["status", "--porcelain"], gitOpts(cwd));
	return output.trim().length > 0;
}

/**
 * Mint a work-branch name.
 *
 * Issue #466 (ADR 0026 D1): the name is generated by the CALLER, not inside
 * `createWorkBranch`, because the durable head-state record must name the branch
 * it is about and is written BEFORE the branch exists (the write-ahead property
 * that makes a crash inside `createWorkBranch` recoverable). This function is
 * the only producer of the `brl-subagent-` prefix in the source tree.
 */
export function newWorkBranchName(): string {
	return "brl-subagent-" + crypto.randomUUID().slice(0, 8);
}

/**
 * The branch HEAD points at, and whether it has a commit yet.
 *
 * `branch` is undefined for a detached HEAD. `unborn` is true when HEAD is a
 * symbolic ref to a branch that does not exist (a branch deleted while it was
 * checked out): `git checkout <some-branch>` still works there, but
 * `git status --porcelain` reports every tracked file as changed, so callers
 * that gate on a clean tree must know the difference.
 */
export interface HeadBranch {
	branch: string | undefined;
	unborn: boolean;
}

/** Read the current HEAD branch tolerate-ably (detached and unborn included).
 *
 * `timeoutMs` exists for the #474 probe, which must keep its own short bound:
 * the detached/unborn semantics belong here (a second copy of "a failed
 * symbolic-ref read means detached" is exactly the drift this helper
 * prevents), but the probe's budget is not the 10 s the lifecycle calls use.
 */
export function getHeadBranch(cwd: string, timeoutMs: number = GIT_TIMEOUT_MS): HeadBranch {
	let branch: string | undefined;
	try {
		branch = execFileSync("git", ["symbolic-ref", "--short", "-q", "HEAD"], gitOpts(cwd, timeoutMs)).trim() || undefined;
	} catch {
		// Detached (or not a repo): no symbolic ref to read.
		branch = undefined;
	}
	let unborn = false;
	try {
		execFileSync("git", ["rev-parse", "--verify", "-q", "HEAD"], gitOpts(cwd, timeoutMs));
	} catch {
		unborn = true;
	}
	return { branch, unborn };
}

/** The repository's work branches (`brl-subagent-*`), short names. */
export function listWorkBranches(cwd: string): string[] {
	const output = execFileSync("git", ["branch", "--list", "brl-subagent-*", "--format=%(refname:short)"], gitOpts(cwd));
	return output
		.split("\n")
		.map((line) => line.trim())
		.filter((line) => line.length > 0);
}

/**
 * Create a work branch from the given base branch.
 * Returns { ok: true, branch } on success, { ok: false, error } on failure.
 *
 * Issue #466: `branch` is a parameter (defaulted for existing callers) so a
 * caller can record the name in the durable head state BEFORE this runs.
 */
export function createWorkBranch(
	cwd: string,
	baseBranch: string,
	branch: string = newWorkBranchName(),
): { ok: true; branch: string } | { ok: false; error: string } {
	try {
		execFileSync("git", ["checkout", "-b", branch, baseBranch], gitOpts(cwd));
		return { ok: true, branch };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Capture the unified diff between baseBranch and HEAD.
 * Returns { ok: true, diff } on success, { ok: false, error } on failure.
 */
export function captureDiff(
	cwd: string,
	baseBranch: string,
): { ok: true; diff: string } | { ok: false; error: string } {
	try {
		const output = execFileSync("git", ["diff", `${baseBranch}...HEAD`], gitOpts(cwd));
		return { ok: true, diff: output };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Switch to an existing branch.
 * Returns { ok: true } on success, { ok: false, error } on failure.
 */
export function switchToBranch(
	cwd: string,
	branch: string,
): { ok: true } | { ok: false; error: string } {
	try {
		execFileSync("git", ["checkout", branch], gitOpts(cwd));
		return { ok: true };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Restore HEAD to the state captured by getHeadState.
 * Detached starts are re-detached at the captured sha (`git checkout
 * --detach <sha>`) instead of switching to the useless "HEAD" pseudo-ref;
 * attached starts switch back to the original branch.
 * Returns { ok: true } on success, { ok: false, error } on failure.
 */
export function restoreHead(
	cwd: string,
	state: HeadState,
): { ok: true } | { ok: false; error: string } {
	try {
		const args = state.detached
			? ["checkout", "--detach", state.sha]
			: ["checkout", state.branch];
		execFileSync("git", args, gitOpts(cwd));
		return { ok: true };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Merge a work branch into the current branch.
 * Uses --no-edit to prevent opening an editor.
 * Returns { ok: true } on success, { ok: false, error } on failure.
 */
export function mergeWorkBranch(
	cwd: string,
	branch: string,
): { ok: true } | { ok: false; error: string } {
	try {
		execFileSync("git", ["merge", branch, "--no-edit"], gitOpts(cwd));
		return { ok: true };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Delete a branch.
 * Returns { ok: true } on success, { ok: false, error } on failure.
 */
export function deleteBranch(
	cwd: string,
	branch: string,
): { ok: true } | { ok: false; error: string } {
	try {
		execFileSync("git", ["branch", "-D", branch], gitOpts(cwd));
		return { ok: true };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Stage and commit ALL changes (tracked + untracked) on the current branch.
 * Used by background gitMode=branch teardown: the agent's work is committed to
 * the work branch BEFORE the diff is captured and the branch is discarded —
 * `git diff base...HEAD` only sees committed changes, and switching back with
 * uncommitted edits would carry them into the base working tree (C1).
 * Returns { ok: true, sha } on success, { ok: false, error } on failure
 * (e.g. no git identity configured).
 */
export function commitAll(
	cwd: string,
	message: string,
): { ok: true; sha: string } | { ok: false; error: string } {
	try {
		execFileSync("git", ["add", "-A"], gitOpts(cwd));
		execFileSync("git", ["commit", "-m", message], gitOpts(cwd));
		const sha = execFileSync("git", ["rev-parse", "HEAD"], gitOpts(cwd)).trim();
		return { ok: true, sha };
	} catch (err) {
		return { ok: false, error: (err as Error).message };
	}
}

/**
 * Capture the WORKING-TREE diff (unstaged + staged + untracked, i.e.
 * everything `git diff base...HEAD` misses when the agent never committed).
 * Untracked files are surfaced via intent-to-add (`git add -N`) WITHOUT
 * staging their content, and the index is restored to its original state —
 * the intent-to-add marks are removed with a path-limited reset that leaves
 * genuinely staged entries untouched. Returns the merged patch text, or
 * undefined when the tree is clean.
 */
export function captureWorkingDiff(cwd: string): string | undefined {
	let untracked: string[] = [];
	try {
		// Identify untracked files FIRST — only these need intent-to-add marks.
		untracked = execFileSync("git", ["ls-files", "--others", "--exclude-standard"], gitOpts(cwd))
			.toString().split("\n").filter(Boolean);
	} catch {
		return undefined;
	}
	try {
		// Capture staged + unstaged (tracked) first — no index mutation yet.
		const unstaged = execFileSync("git", ["diff"], gitOpts(cwd)).toString();
		const staged = execFileSync("git", ["diff", "--cached"], gitOpts(cwd)).toString();
		let untrackedDiff = "";
		if (untracked.length > 0) {
			// Surface untracked files via intent-to-add, WITHOUT staging content.
			execFileSync("git", ["add", "-N", "--", ...untracked], gitOpts(cwd));
			untrackedDiff = execFileSync("git", ["diff"], gitOpts(cwd)).toString();
			// Remove ONLY the intent-to-add marks — real staged entries are preserved.
			execFileSync("git", ["reset", "-q", "--", ...untracked], gitOpts(cwd));
		}
		const merged = `${unstaged}${untrackedDiff}${staged}`.trim();
		return merged.length > 0 ? merged : undefined;
	} catch {
		try {
			// Best-effort index restore even if a diff command failed mid-way.
			if (untracked.length > 0) execFileSync("git", ["reset", "-q", "--", ...untracked], gitOpts(cwd));
		} catch { /* ignore */ }
		return undefined;
	}
}

// ---------------------------------------------------------------------------
// Read-only worktree probe (issue #474)
// ---------------------------------------------------------------------------

/**
 * One git command inside the probe. The probe makes FIVE short reads —
 * `rev-parse`, `status`, the two inside `getHeadBranch` (`symbolic-ref` +
 * `rev-parse --verify`), and `diff --shortstat` — so its worst case is
 * 5 × this bound (~15 s) on a host where every one hangs, and milliseconds
 * when git is healthy. The bound is per command on purpose: the branch reads
 * are shared with `getHeadBranch` (their detached/unborn semantics are not
 * re-implemented here), and the failure path may wait, but not forever.
 */
const PROBE_TIMEOUT_MS = 3_000;

/**
 * Every probe read is a READ, and `git status` / `git diff` are only read-only
 * by intent: without `GIT_OPTIONAL_LOCKS=0` git refreshes `.git/index` as an
 * optional side effect, so the "read" moves a file in the tree it is reporting
 * (measured: identical bytes, changed mtime — the index-safe test pins both).
 * `LC_ALL=C` pins `--shortstat` to the parseable English wording.
 */
function probeOpts(cwd: string) {
	return {
		cwd,
		encoding: "utf-8" as const,
		timeout: PROBE_TIMEOUT_MS,
		stdio: ["ignore", "pipe", "pipe"] as ["ignore", "pipe", "pipe"],
		env: { ...process.env, GIT_OPTIONAL_LOCKS: "0", LC_ALL: "C" },
	};
}

/** What the probe found, or why it could not look (issue #474). */
export type WorktreeProbe =
	| {
			kind: "ok";
			/** The checked-out branch; undefined when HEAD is detached. */
			branch: string | undefined;
			detached: boolean;
			/** HEAD is a symbolic ref to a branch with no commit yet. */
			unborn: boolean;
			/** Entries with worktree changes, plus untracked files. */
			dirtyFiles: number;
			/** Entries with index changes (never the `??` untracked rows). */
			stagedFiles: number;
			/** Tracked unstaged line counts; absent when `git diff` reported none (or failed). */
			insertions?: number;
			deletions?: number;
	  }
	/** The cwd is not inside a git repository (or is a bare repo). */
	| { kind: "not-repo" }
	/** The repository could not be read; `reason` is git's own diagnosis. */
	| { kind: "unavailable"; reason: string };

/** Longest reason reported — the block rides a tool result, not a log file. */
const MAX_PROBE_REASON_LENGTH = 160;

/**
 * The first line git printed, as the reason. git's stderr is the diagnosable
 * half AND the safe half: the wrapper message `execFileSync` builds names the
 * command line, and for a vanished cwd it names the absolute path (F7 — the
 * failure path must never echo the cwd raw). Measured: an `ENOENT`/`ETIMEDOUT`
 * spawn carries an EMPTY stderr, so those classify below instead.
 *
 * A deleted cwd and a missing git both surface as `ENOENT` (node reports the
 * failed spawn, not which half failed), so the cwd is probed to tell them
 * apart — the two need different fixes and the report is the reader's only
 * evidence.
 */
function probeFailureReason(cwd: string, err: unknown): string {
	const stderr = (err as { stderr?: unknown } | null)?.stderr;
	const text = typeof stderr === "string" ? stderr : stderr ? String(stderr) : "";
	const line = text
		.split("\n")
		.map((part) => part.trim())
		.find((part) => part.length > 0);
	if (line) {
		return line.length > MAX_PROBE_REASON_LENGTH ? `${line.slice(0, MAX_PROBE_REASON_LENGTH)}…` : line;
	}
	const code = (err as { code?: unknown } | null)?.code;
	if (code === "ETIMEDOUT") return "git timed out";
	if (code === "ENOENT") return fs.existsSync(cwd) ? "git is not installed" : "cwd does not exist";
	if (typeof code === "string") return `git failed (${code})`;
	return "git failed";
}

/**
 * Classify a failed `rev-parse --is-inside-work-tree`: git's own "not a git
 * repository" is the ONE expected failure (it is the answer, not an error),
 * and everything else — a deleted cwd, a missing git, a timeout — is
 * unavailable with a reason. `getRepoRoot`'s catch-all is deliberately NOT
 * reused: it returns undefined for both cases, which would report a hung git
 * as "not a git repository".
 */
function classifyProbeFailure(cwd: string, err: unknown): WorktreeProbe {
	const reason = probeFailureReason(cwd, err);
	if (/not a git repository/i.test(reason)) return { kind: "not-repo" };
	return { kind: "unavailable", reason };
}

/**
 * Count `git status --porcelain -z` rows, split into worktree-dirty and staged.
 *
 * `-z` means NUL-separated records and never-quoted paths, and it changes the
 * rename shape: `R  <new>\0<old>` — the destination row followed by a BARE
 * source path. Counting NUL fields would read one `git mv` as two dirty files,
 * so the source field is skipped (and only renames/copies emit one).
 */
function countStatusEntries(porcelain: string): { dirty: number; staged: number } {
	let dirty = 0;
	let staged = 0;
	let skipNext = false;
	for (const field of porcelain.split("\0")) {
		if (field.length === 0) continue;
		if (skipNext) {
			skipNext = false;
			continue;
		}
		const x = field[0];
		const y = field[1];
		if (x === undefined || y === undefined) continue;
		if (x === "?") {
			dirty++; // untracked file (or, with -uall, every file in an untracked dir)
			continue;
		}
		if (x === "R" || x === "C") skipNext = true;
		if (y !== " ") dirty++;
		if (x !== " ") staged++;
	}
	return { dirty, staged };
}

/** ` 3 files changed, 10 insertions(+), 2 deletions(-)` → line counts, or undefined. */
function parseShortstat(output: string): { insertions: number; deletions: number } | undefined {
	if (!/\d+ files? changed/.test(output)) return undefined;
	const insertions = /(\d+) insertions?\(\+\)/.exec(output);
	const deletions = /(\d+) deletions?\(-\)/.exec(output);
	return {
		insertions: insertions ? Number(insertions[1]) : 0,
		deletions: deletions ? Number(deletions[1]) : 0,
	};
}

/**
 * Report the state of the worktree at `cwd` — branch, dirty/staged counts,
 * unstaged line counts — for the failure report (issue #474). NEVER THROWS:
 * every failure is a classified value.
 *
 * This is a BEST-EFFORT read of a moving tree, not an atomic snapshot: the
 * status and the diff are two commands, so a write between them can make the
 * counts disagree with each other. It is deliberately not made consistent —
 * the reader is a conductor deciding whether to look before reusing the tree,
 * and a torn count is still evidence, while a lock (or a second retry) on the
 * failure path is not.
 */
export function probeWorktree(cwd: string): WorktreeProbe {
	let inside: string;
	try {
		inside = execFileSync("git", ["rev-parse", "--is-inside-work-tree"], probeOpts(cwd)).trim();
	} catch (err) {
		return classifyProbeFailure(cwd, err);
	}
	// A bare repository exits 0 with "false" — there is no worktree to report.
	if (inside !== "true") return { kind: "not-repo" };

	let porcelain: string;
	try {
		porcelain = execFileSync("git", ["status", "--porcelain", "-z", "-uall"], probeOpts(cwd));
	} catch (err) {
		return { kind: "unavailable", reason: probeFailureReason(cwd, err) };
	}
	const { dirty, staged } = countStatusEntries(porcelain);
	// Undefined branch + not unborn = detached HEAD (getHeadBranch owns that reading).
	const head = getHeadBranch(cwd, PROBE_TIMEOUT_MS);

	// The line counts are the optional half: losing them costs a detail, never
	// the report, so a failed `diff` degrades the block instead of emptying it.
	let lineCounts: { insertions: number; deletions: number } | undefined;
	try {
		lineCounts = parseShortstat(execFileSync("git", ["diff", "--shortstat"], probeOpts(cwd)));
	} catch {
		lineCounts = undefined;
	}

	return {
		kind: "ok",
		branch: head.branch,
		detached: head.branch === undefined && !head.unborn,
		unborn: head.unborn,
		dirtyFiles: dirty,
		stagedFiles: staged,
		...(lineCounts ?? {}),
	};
}
